import React, { useState } from 'react';
import { useQuery } from '@tanstack/react-query';
import { useNavigate } from 'react-router-dom';
import { apiClient } from '../api/client';
import SimulatedBadge from '../components/common/SimulatedBadge';
import LoadingSpinner from '../components/common/LoadingSpinner';
import ErrorDisplay from '../components/common/ErrorDisplay';

export default function Recommendation() {
  const navigate = useNavigate();
  const [filterPriority, setFilterPriority] = useState<string>('ALL');

  const { data: recommendations, isLoading, error } = useQuery({
    queryKey: ['recommendations'],
    queryFn: () => apiClient.fetchRecommendations(),
  });

  if (isLoading) return <LoadingSpinner />;
  if (error) return <ErrorDisplay message={(error as Error).message} />;

  const recList = Array.isArray(recommendations) ? recommendations : [];

  const filteredRecs = recList.filter((r: any) => {
    if (filterPriority !== 'ALL' && !r.priority.includes(filterPriority)) return false;
    return true;
  });

  const getPriorityBadge = (priority: string) => {
    switch (priority) {
      case 'P1_CRITICAL':
      case 'P1':
        return 'bg-red-950/80 text-red-300 border-red-700';
      case 'P2_HIGH':
      case 'P2':
        return 'bg-amber-950/80 text-amber-300 border-amber-700';
      default:
        return 'bg-blue-950/80 text-blue-300 border-blue-700';
    }
  };

  return (
    <div className="space-y-6">
      {/* Top Banner */}
      <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center p-4 bg-slate-800 rounded-lg border border-slate-700 shadow gap-4">
        <div>
          <div className="flex items-center gap-3">
            <h2 className="text-2xl font-bold text-white">Actionable Operational Recommendations</h2>
            <SimulatedBadge />
          </div>
          <p className="text-slate-400 text-sm mt-1">
            Tactical decision support generated by the LangGraph 6-Agent pipeline, prioritized for immediate municipal response.
          </p>
        </div>

        {/* Priority Filter */}
        <div className="flex items-center gap-2">
          {['ALL', 'CRITICAL', 'HIGH'].map((p) => (
            <button
              key={p}
              onClick={() => setFilterPriority(p)}
              className={`px-3 py-1.5 rounded text-xs font-semibold transition ${
                filterPriority === p
                  ? 'bg-blue-600 text-white shadow'
                  : 'bg-slate-700 text-slate-300 hover:bg-slate-600'
              }`}
            >
              {p === 'ALL' ? 'All Priorities' : p}
            </button>
          ))}
        </div>
      </div>

      {/* Recommendations Cards List */}
      <div className="space-y-4">
        {filteredRecs.map((rec: any, idx: number) => {
          const isCritical = rec.priority.includes('P1') || rec.priority.includes('CRITICAL');
          return (
            <div
              key={rec.id || idx}
              className={`p-5 rounded-lg border shadow space-y-4 transition ${
                isCritical
                  ? 'bg-slate-900 border-red-900/60 hover:border-red-700/80'
                  : 'bg-slate-900 border-slate-800 hover:border-slate-700'
              }`}
            >
              {/* Header */}
              <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center gap-2">
                <div className="flex items-center gap-2.5">
                  <span
                    className={`text-[10px] font-mono px-2.5 py-0.5 rounded border font-bold ${getPriorityBadge(
                      rec.priority
                    )}`}
                  >
                    {rec.priority}
                  </span>
                  <span className="text-sm font-bold text-white">{rec.recommendation_type}</span>
                  {rec.ward_id && (
                    <span className="text-xs text-blue-400 font-mono">[{rec.ward_id}]</span>
                  )}
                </div>

                <div className="text-xs text-slate-500 font-mono">ID: {rec.id}</div>
              </div>

              {/* Description */}
              <p className="text-sm text-slate-200 leading-relaxed">{rec.description}</p>

              {/* Tactical Actions Detail */}
              {rec.actions && Object.keys(rec.actions).length > 0 && (
                <div className="bg-slate-950 p-3 rounded border border-slate-800/80 space-y-2">
                  <div className="text-[11px] font-semibold text-slate-400 uppercase tracking-wider">
                    Recommended Execution Parameters:
                  </div>
                  <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-2 text-xs font-mono">
                    {Object.entries(rec.actions).map(([key, val]) => (
                      <div key={key} className="p-2 bg-slate-900/80 rounded border border-slate-800">
                        <span className="text-slate-400 text-[10px] block uppercase">
                          {key.replace(/_/g, ' ')}
                        </span>
                        <span className="text-cyan-300 font-semibold text-xs">
                          {Array.isArray(val) ? val.join(', ') : String(val)}
                        </span>
                      </div>
                    ))}
                  </div>
                </div>
              )}

              {/* Action Buttons */}
              <div className="flex flex-wrap items-center justify-between pt-2 border-t border-slate-800 gap-3">
                <div className="text-xs text-slate-400">
                  Authority Gate: <span className="text-amber-400">Requires Emergency Coordinator Sign-off</span>
                </div>
                <div className="flex items-center gap-2">
                  <button
                    onClick={() => navigate('/routing')}
                    className="px-3 py-1.5 bg-slate-800 hover:bg-slate-700 text-slate-200 rounded text-xs font-medium transition"
                  >
                    Calculate Evacuation Route &rarr;
                  </button>
                  <button
                    onClick={() => navigate('/review')}
                    className="px-3 py-1.5 bg-blue-600 hover:bg-blue-500 text-white rounded text-xs font-semibold shadow transition"
                  >
                    Open Review Console &rarr;
                  </button>
                </div>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
}
